"""Node credentials registry.

Single source of truth for node-owned credentials that must NEVER be
written or deleted through sensitive_service / public API. The only
legitimate writer is NodeKeyService via its independent SQL path
(see NodeKeyService._write_one_credential_direct).

1.5.2 hotfix P0: this registry replaces per-info_type hardcoded checks
that were scattered across sensitive_service.py (DB layer, 2 sites)
and api_router.py (API layer, 3 sites). To add a new node-owned
credential type, add one entry here — no other code changes needed.
"""

# 节点身份凭证注册表——所有"由 NodeKeyService 管理的系统凭证"统一在这里登记。
# 每条记录包含：(info_type, info_owner)
#
# 1.5.4 新增：
#   - __DEFAULT_NODE_PUB__ / default_node_priv：
#     所有 1.5.4+ 节点共享的固定 RSA 密钥对，用于 free mode 的 ext03 外层 RSA 加密。
#     PEM 由 NodeKeyService 顶部常量 DEFAULT_NODE_PEM_PUB/PRIV 硬编码，
#     首次启动时 ensure_default_keys() 写入 SQLCipher。
NODE_CREDENTIALS_REGISTRY = {
    "__NODE_PUB__":         "__NODE_PUB__",         # 节点 RSA 公钥（暴露给 skill store 用于验签）
    "node_priv":            "SYSTEM",               # 节点 RSA 私钥（用于 unseal ext03 AES key）
    "__DEFAULT_NODE_PUB__": "__DEFAULT_NODE_PUB__", # 1.5.4+：共享默认公钥（free mode 用），查询方通过 info_owner 区分
    "default_node_priv":    "SYSTEM",               # 1.5.4+：共享默认私钥（free mode 解 ext03 内层用）
}


def is_node_credential(info_type: str) -> bool:
    """Check if info_type belongs to a node-owned credential.

    Returns True for any info_type registered in NODE_CREDENTIALS_REGISTRY.
    Used by DB layer (sensitive_service) and API layer (api_router) to
    refuse write/delete requests before they reach SQLCipher.
    """
    if info_type is None:
        return False
    return info_type in NODE_CREDENTIALS_REGISTRY


def node_credential_owner(info_type: str):
    """Return the canonical info_owner for a registered node credential.

    Used by NodeKeyService._write_one_credential_direct to locate the
    existing record (info_type + info_owner is the unique key for
    non-diff records).
    """
    return NODE_CREDENTIALS_REGISTRY.get(info_type)


def assert_writable_by_node_key_service(info_type: str) -> None:
    """Raise SensitiveServiceError if info_type is a node credential.

    This is the single entry point invoked by sensitive_service
    (_save_to_mgc_info_1, _delete_from_mgc_info_1) and api_router
    (save / save_silent / delete). Centralizing the check here
    ensures the same protection regardless of which entry the
    attacker uses.
    """
    if is_node_credential(info_type):
        # Lazy import to avoid circular dependency at module load time.
        from mgc.core.mgc_service.sensitive_service import SensitiveServiceError
        raise SensitiveServiceError(
            f"NODE_KEY_WRITE_PROTECTED: '{info_type}' is system-managed. "
            f"It is generated by NodeKeyService and cannot be written "
            f"via sensitive_service / public API."
        )
